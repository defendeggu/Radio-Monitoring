#!/usr/bin/env bash
#
# Create or complete the .env file with all required settings and secrets.
#
#   ./scripts/setup-env.sh            # create .env or add missing variables
#   ./scripts/setup-env.sh --light    # new .env for the light profile (no ELK, SQLite)
#
# Existing values are never changed. New secrets are random (openssl).
# The file is written with permissions 600.

set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."
ENV_FILE=".env"
LIGHT=0
[[ "${1:-}" == "--light" ]] && LIGHT=1

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

secret() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

# Bind-mounted data directories: create them now, otherwise Docker creates them
# as root on the first start and the API (UID 1000) cannot write recordings.
mkdir -p recordings captures
for dir in recordings captures; do
  if [[ "$(stat -c %u "$dir")" != 1000 ]]; then
    echo "WARNING: ./$dir is not owned by UID 1000 (the API user) — recordings will fail."
    echo "         Fix: sudo chown 1000:1000 $dir"
  fi
done

touch "$ENV_FILE"
chmod 600 "$ENV_FILE"

added=()
ensure() {
  local name="$1" value="$2"
  if ! grep -qE "^${name}=" "$ENV_FILE"; then
    printf '%s=%s\n' "$name" "$value" >> "$ENV_FILE"
    added+=("$name")
  elif grep -qE "^${name}=(changeme.*)?$" "$ENV_FILE" && [[ "${3:-}" == "secret" ]]; then
    # replace empty or placeholder secrets
    sed -i "s|^${name}=.*|${name}=${value}|" "$ENV_FILE"
    added+=("$name (replaced placeholder)")
  fi
}

grep -q "RadioMoni" "$ENV_FILE" || printf '# RadioMoni configuration — generated by scripts/setup-env.sh. Never commit this file.\n' >> "$ENV_FILE"

# --- deployment ---------------------------------------------------------------
if [[ $LIGHT == 1 ]]; then
  ensure COMPOSE_PROFILES ""
  ensure STORAGE_BACKEND sqlite
else
  ensure COMPOSE_PROFILES elk
  ensure STORAGE_BACKEND elasticsearch
fi
ensure WEB_PORT 8080
ensure TZ "Europe/Zurich"

# --- API ----------------------------------------------------------------------
ensure API_KEYS "$(secret 43)" secret
ensure REDIS_PASSWORD "$(secret 32)" secret

# --- ELK ----------------------------------------------------------------------
ensure ELASTIC_PASSWORD "$(secret 32)" secret
ensure KIBANA_SYSTEM_PASSWORD "$(secret 32)" secret
ensure LOGSTASH_SYSTEM_PASSWORD "$(secret 32)" secret
ensure LOGSTASH_WRITER_PASSWORD "$(secret 32)" secret
ensure LOGSTASH_HTTP_PASSWORD "$(secret 32)" secret
ensure BEATS_SYSTEM_PASSWORD "$(secret 32)" secret
ensure BEATS_WRITER_PASSWORD "$(secret 32)" secret
ensure RADIO_API_PASSWORD "$(secret 32)" secret
ensure KIBANA_ENCRYPTION_KEY "$(openssl rand -hex 32)" secret

if ((${#added[@]})); then
  echo "Updated $ENV_FILE:"
  printf '  + %s\n' "${added[@]}"
else
  echo "$ENV_FILE is complete — nothing to do."
fi
echo
echo "Your API key (enter it in the web UI under Settings):"
grep -E '^API_KEYS=' "$ENV_FILE" | cut -d= -f2 | cut -d, -f1
