#!/bin/bash

echo "========================================="
echo "Radio Transcription System - Setup"
echo "========================================="
echo ""

# Check if running on Linux
if [[ "$OSTYPE" != "linux-gnu"* ]]; then
    echo "Warning: This setup script is designed for Linux."
    echo "For macOS, please install dependencies manually using Homebrew."
    echo ""
fi

# Check if running as root
if [[ $EUID -eq 0 ]]; then
   echo "Please do not run this script as root"
   exit 1
fi

# Install system dependencies
echo "Installing system dependencies..."
echo "You may be prompted for your sudo password."
echo ""

sudo apt-get update
sudo apt-get install -y \
    libusb-1.0-0-dev \
    libhackrf-dev \
    hackrf \
    rtl-sdr \
    librtlsdr-dev \
    build-essential \
    python3-pip \
    python3-venv \
    direwolf \
    multimon-ng \
    libasound2-dev \
    cmake

# Create virtual environment
echo ""
echo "Creating Python virtual environment..."
python3 -m venv venv

# Activate virtual environment
source venv/bin/activate

# Install Python dependencies
echo ""
echo "Installing Python dependencies..."
pip install --upgrade pip
pip install -r requirements.txt

# Create directories
echo ""
echo "Creating directories..."
mkdir -p recordings

# Copy environment file
if [ ! -f .env ]; then
    echo ""
    echo "Creating .env file..."
    cp .env.example .env
    echo "Please edit .env to customize your configuration"
fi

# Generate API keys for security
echo ""
echo "Generating API keys for secure API access..."
if command -v python3 &> /dev/null; then
    API_KEY_OUTPUT=$(python3 scripts/generate_api_keys.py 2>/dev/null)
    if [ $? -eq 0 ]; then
        # Extract the API_KEYS line from the output
        API_KEYS_LINE=$(echo "$API_KEY_OUTPUT" | grep "^API_KEYS=")

        # Append to .env if API_KEYS not already set
        if ! grep -q "^API_KEYS=" .env 2>/dev/null; then
            echo "" >> .env
            echo "# API Security - Generated by setup.sh" >> .env
            echo "$API_KEYS_LINE" >> .env
            echo "API keys generated and added to .env"
            echo ""
            echo "========================================="
            echo "⚠️  IMPORTANT: SAVE YOUR API KEYS ⚠️"
            echo "========================================="
            echo "$API_KEY_OUTPUT"
            echo "========================================="
            echo ""
            echo "These keys are required to access the API!"
            echo "Save them to your password manager now."
        else
            echo "API_KEYS already configured in .env"
        fi
    else
        echo "Warning: Could not generate API keys automatically"
        echo "Run manually: python3 scripts/generate_api_keys.py"
    fi
else
    echo "Warning: Python3 not found, skipping API key generation"
    echo "Generate API keys manually after setup"
fi

# Add user to plugdev group for USB access
echo ""
echo "Setting up USB permissions for SDR devices (HackRF/RTL-SDR)..."
sudo usermod -a -G plugdev $USER

# Create udev rules for HackRF
echo ""
echo "Creating udev rules for HackRF..."
sudo tee /etc/udev/rules.d/53-hackrf.rules > /dev/null <<EOF
ATTR{idVendor}=="1d50", ATTR{idProduct}=="6089", SYMLINK+="hackrf-one-%k", MODE="660", GROUP="plugdev"
ATTR{idVendor}=="1d50", ATTR{idProduct}=="604b", SYMLINK+="hackrf-one-%k", MODE="660", GROUP="plugdev"
ATTR{idVendor}=="1d50", ATTR{idProduct}=="6062", SYMLINK+="rad1o-%k", MODE="660", GROUP="plugdev"
ATTR{idVendor}=="1d50", ATTR{idProduct}=="cc15", SYMLINK+="rad1o-%k", MODE="660", GROUP="plugdev"
EOF

# Create udev rules for RTL-SDR
echo ""
echo "Creating udev rules for RTL-SDR..."
sudo tee /etc/udev/rules.d/20-rtlsdr.rules > /dev/null <<EOF
SUBSYSTEM=="usb", ATTRS{idVendor}=="0bda", ATTRS{idProduct}=="2832", GROUP="plugdev", MODE="0666", SYMLINK+="rtl_sdr"
SUBSYSTEM=="usb", ATTRS{idVendor}=="0bda", ATTRS{idProduct}=="2838", GROUP="plugdev", MODE="0666", SYMLINK+="rtl_sdr"
EOF

sudo udevadm control --reload-rules
sudo udevadm trigger

# Test SDR connection
echo ""
echo "Testing SDR device connection..."
SDR_FOUND=false

if command -v hackrf_info &> /dev/null; then
    if hackrf_info &> /dev/null; then
        echo "✓ HackRF detected"
        SDR_FOUND=true
    fi
fi

if command -v rtl_test &> /dev/null; then
    if timeout 2 rtl_test -t &> /dev/null; then
        echo "✓ RTL-SDR detected"
        SDR_FOUND=true
    fi
fi

if [ "$SDR_FOUND" = false ]; then
    echo "Warning: No SDR device detected. Please connect your HackRF or RTL-SDR device."
fi

# Run tests to verify installation
echo ""
echo "Running tests to verify installation..."
if pytest --version &> /dev/null; then
    echo "Running test suite..."
    if pytest -q; then
        echo "✓ All tests passed!"
    else
        echo "⚠ Some tests failed. This may be OK if you don't have SDR hardware connected."
        echo "  The system will still work in simulation mode."
    fi
else
    echo "Warning: pytest not found. Skipping test verification."
fi

# Run type checking
echo ""
echo "Running type checking..."
if command -v mypy &> /dev/null; then
    if mypy --version &> /dev/null; then
        if ./scripts/run_mypy.sh &> /dev/null; then
            echo "✓ Type checking passed!"
        else
            echo "⚠ Type checking found some issues (see scripts/run_mypy.sh for details)"
        fi
    fi
else
    echo "Info: mypy not found in PATH. Type checking skipped."
fi

echo ""
echo "========================================="
echo "Setup Complete!"
echo "========================================="
echo ""
echo "✓ System dependencies installed"
echo "✓ Python virtual environment created"
echo "✓ Python packages installed"
echo "✓ USB permissions configured"
echo "✓ API keys generated"
echo "✓ Test suite verified"
echo ""
echo "Next steps:"
echo "1. Log out and log back in for USB permissions to take effect"
echo "2. Connect your HackRF or RTL-SDR device"
echo "3. Run: source venv/bin/activate"
echo "4. Run: ./scripts/start.sh"
echo ""
echo "For development:"
echo "  pytest                    # Run test suite"
echo "  ./scripts/run_mypy.sh     # Type checking"
echo "  ./scripts/run_coverage.sh # Test coverage"
echo "  python api_service.py     # Start dev server"
echo ""
echo "For production with ELK stack:"
echo "  docker compose -f docker-compose.yml -f docker-compose.elk.yml up -d"
echo ""
